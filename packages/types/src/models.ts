/**
 * Origin of the analyzed content or scan request.
 */
export type InputSource = 'SHARED_TEXT' | 'PROCESS_TEXT' | 'PASTED' | 'QR_CODE' | 'WEB_PASTE';

/**
 * Severity level of an individual finding.
 */
export type Severity = 'INFO' | 'LOW' | 'MEDIUM' | 'HIGH';

/**
 * Reliability rating of an analysis rule.
 */
export type Confidence = 'LOW' | 'MEDIUM' | 'HIGH';

/**
 * Categorical risk tier calculated from aggregated scores.
 */
export type RiskBand = 'NO_WARNING_SIGNS' | 'NOTICE' | 'CAUTION' | 'STRONG_WARNING';

/**
 * Stable 25 rule identifiers.
 */
export type RuleId =
  | 'U001' | 'U002' | 'U003' | 'U004' | 'U005' | 'U006' | 'U007' | 'U008'
  | 'U009' | 'U010' | 'U011' | 'U012' | 'U013' | 'U014' | 'U015' | 'U016' | 'U017'
  | 'M001' | 'M002' | 'M003' | 'M004' | 'M005' | 'M006'
  | 'Q001' | 'Q002';

/**
 * Standard keys identifying evidence items.
 */
export type EvidenceKey =
  | 'OBSERVED_HOST'
  | 'DECODED_HOST'
  | 'REGISTRABLE_DOMAIN'
  | 'SCHEME'
  | 'PORT'
  | 'SCRIPTS'
  | 'CHARACTERS'
  | 'MATCHED_BRAND'
  | 'OFFICIAL_DOMAIN'
  | 'MATCH_KIND'
  | 'LABEL_COUNT'
  | 'SERVICE'
  | 'PARAM_NAME'
  | 'IP_FORM'
  | 'PHRASE'
  | 'WORD'
  | 'PAYLOAD_TYPE'
  | 'USERINFO_PRESENT';

/**
 * Concrete observable finding artifact.
 */
export interface EvidenceDto {
  key: EvidenceKey;
  value: string;
}

/**
 * An individual heuristic finding generated by an analysis rule.
 */
export interface FindingDto {
  ruleId: RuleId;
  severity: Severity;
  confidence: Confidence;
  score: number;
  evidence: EvidenceDto[];
}

/**
 * Composite score and associated band.
 */
export interface RiskAssessmentDto {
  score: number;
  band: RiskBand;
}

/**
 * Detailed analysis report for a single link.
 */
export interface LinkReportDto {
  displayUrl: string;
  host: string | null;
  decodedHost: string | null;
  registrableDomain: string | null;
  findings: FindingDto[];
  assessment: RiskAssessmentDto;
}

/**
 * Notes regarding limits, truncation, or payload specifics.
 */
export type ReportNoteDto =
  | { type: 'NoLinksFound' }
  | { type: 'InputTruncated' }
  | { type: 'LinksLimitReached'; analysed: number; found: number }
  | { type: 'QrNotALink'; payloadType: string };

/**
 * Complete immutable report matching Kotlin AnalysisReport.
 */
export interface AnalysisReportDto {
  source: InputSource;
  links: LinkReportDto[];
  messageFindings: FindingDto[];
  overall: RiskAssessmentDto;
  notes: ReportNoteDto[];
  analyzerVersion: number;
}

/**
 * Database record for the 'scans' table.
 */
export interface ScanRecord {
  id: string;
  user_id: string;
  source: InputSource;
  input_text: string;
  overall_score: number;
  risk_band: RiskBand;
  links_count: number;
  report_json: AnalysisReportDto;
  device_origin: 'ANDROID' | 'WEB';
  created_at: string;
}

/**
 * Database record for the 'profiles' table.
 */
export interface ProfileRecord {
  id: string;
  email: string | null;
  is_anonymous: boolean;
  pairing_code: string | null;
  pairing_code_expires_at: string | null;
  device_sync_enabled: boolean;
  created_at: string;
  updated_at: string;
}
